import { strict as assert } from 'node:assert';
import { createCatalogPager } from '../main/services/catalog-bridge-page';
import type { CatalogProduct, CatalogGroup, BusinessRequest, TrustedContext } from '../main/contracts/businessV2';
const context: TrustedContext = { installationId:'store_1', sessionId:'session_1', principal:{kind:'machine',installationId:'store_1',scopes:['catalog.view']},granted:['catalog.get_page'] };
const product = (i:number): CatalogProduct => ({id:`product_${i}`,name:`Pizza ${i}`,sku:`SKU${i}`,categoryName:'Pizza',priceCents:1000,active:true,variants:[{id:`variant_${i}`,name:'Grande',priceCents:2000,active:true}],groupIds:['group_1']});
const group: CatalogGroup = {id:'group_1',name:'Extras',active:true,required:false,minSelection:0,maxSelection:2,addons:[{id:'addon_1',name:'Cheese',priceCents:100,active:true}]};
const req = (snapshotId:string|null=null,cursor:string|null=null): BusinessRequest => ({type:'request',protocol:2,requestId:'request_1',sessionId:context.sessionId,operation:'catalog.get_page',payload:{snapshotId,cursor,limit:25}});
const pager = createCatalogPager(() => ({products:Array.from({length:100},(_,i)=>product(i)),groups:[group]}), {maxPayloadBytes:1100});
const pages: any[] = [];
let snapshotId:string|null=null, cursor:string|null=null;
do { const response = pager.getPage(req(snapshotId,cursor) as Extract<BusinessRequest,{operation:'catalog.get_page'}>,context); assert.equal(response.outcome,'applied'); assert.ok(Buffer.byteLength(JSON.stringify(response)) <= 1100); pages.push(response.result); snapshotId=response.result.snapshotId; cursor=response.result.nextCursor; } while(cursor);
assert.equal(pages.flatMap(p=>p.products).length,100);
assert.equal(pages.flatMap(p=>p.groups).length,1);
const first=pages[0];
assert.equal(new Set(pages.map(p=>p.revision)).size,1);
let current=[product(1)];
const stable=createCatalogPager(()=>({products:current,groups:[]}),{maxPayloadBytes:1100});
const old=stable.getPage(req() as any,context);
assert.equal(old.outcome,'applied');
current=[{...product(1),name:'Changed'},product(2)];
const newPage=stable.getPage(req() as any,context);
assert.equal(newPage.outcome,'applied');
assert.notEqual(old.result.revision,newPage.result.revision);
const expiration=createCatalogPager(()=>({products:Array.from({length:100},(_,i)=>product(i)),groups:[]}),{ttlMs:-1,maxPayloadBytes:1100});
const expired=expiration.getPage(req() as any,context);
assert.equal(expired.outcome,'applied');
assert.equal(expiration.getPage(req(expired.result.snapshotId,expired.result.nextCursor) as any,context).errorCode,'snapshot_expired');
const groupOnly=createCatalogPager(()=>({products:[],groups:Array.from({length:150},(_,i)=>({...group,id:`group_${i}`}))}));
let groupPage=groupOnly.getPage(req() as any,context);
assert.equal(groupPage.outcome,'applied');
let groupCount=0;
while(groupPage.outcome==='applied') {
  assert.equal(groupPage.result.products.length,0);
  groupCount+=groupPage.result.groups.length;
  if(groupPage.result.nextCursor===null) break;
  groupPage=groupOnly.getPage(req(groupPage.result.snapshotId,groupPage.result.nextCursor) as any,context);
}
assert.equal(groupCount,150);
const constrained=createCatalogPager(()=>({products:Array.from({length:100},(_,i)=>product(i)),groups:[]}),{maxPayloadBytes:1100});
for(let i=0;i<4;i++) { const ctx={...context,sessionId:`sess_${i}`}; assert.equal(constrained.getPage({...req(),sessionId:ctx.sessionId} as any,ctx).outcome,'applied'); }
assert.equal(constrained.size(),4);
assert.equal(constrained.getPage(req() as any,context).outcome,'unknown');
const tooLarge=createCatalogPager(()=>({products:[{...product(1),name:'x'.repeat(120)}],groups:[]}),{maxPayloadBytes:256});
assert.equal(tooLarge.getPage(req() as any,context).outcome,'unknown');
assert.equal(pager.getPage(req(snapshotId,'bogus') as any,context).outcome,'not_applied');
assert.equal(pager.getPage(req(snapshotId,first.nextCursor) as any,{...context,sessionId:'session_2'}).outcome,'not_applied');
pager.clear();
assert.equal(pager.getPage(req(snapshotId,first.nextCursor) as any,context).outcome,'not_applied');
console.log('catalog bridge pagination tests passed');
